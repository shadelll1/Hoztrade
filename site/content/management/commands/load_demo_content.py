class Command(BaseCommand):
    help = "Загрузить демо-контент: бренды, акции, новости, советы"

    def handle(self, *args, **options):
        for n, (name, aliases, description) in enumerate(BRANDS, start=1):
            Brand.objects.update_or_create(name=name, defaults={
                "aliases": aliases, "description": description, "sort": n * 10, "is_published": True})
        linked = assign_brands()

        now = timezone.now()
        for item in POSTS:
            promo_days = item.get("promo_days")
            Post.objects.update_or_create(slug=item["slug"], defaults={
                "kind": item["kind"], "title": item["title"], "lead": item["lead"], "body": item["body"],
                "published_at": now - timedelta(days=item["days_ago"]), "is_published": True,
                "promo_until": timezone.localdate() + timedelta(days=promo_days) if promo_days else None,
            })
        self.stdout.write(self.style.SUCCESS(
            f"Брендов: {len(BRANDS)} (привязано товаров: {linked}), публикаций: {len(POSTS)}"))
