def _merge(base, extra):
    """Базовый каталог + расширенный ассортимент. Новые разделы встают перед «Крепёж и инструмент»."""
    merged = {}
    for section, groups in base.items():
        if section == "Крепёж и инструмент":
            for new_section in extra:
                if new_section not in base:
                    merged[new_section] = {g: list(items) for g, items in extra[new_section].items()}
        merged[section] = {g: list(items) for g, items in groups.items()}
        for group, items in extra.get(section, {}).items():
            merged[section].setdefault(group, []).extend(items)
    return merged


CATALOG = _merge(CATALOG, EXTRA)


def _id(*parts):
    return str(uuid.uuid5(NS, "/".join(parts)))


def demo_payload():
    """Посылка для POST /api/v1/catalog/ (без поля full: демо не снимает с публикации остальное)."""
    categories, products, prices, stock = [], [], [], []
    for section, groups in CATALOG.items():
        section_id = _id(section)
        categories.append({"id": section_id, "parent_id": None, "name": section})
        for group, items in groups.items():
            group_id = _id(section, group)
            categories.append({"id": group_id, "parent_id": section_id, "name": group})
            for name, sku, unit, weight, volume, retail, wholesale, qty in items:
                pid = _id(section, group, sku)
                products.append({
                    "id": pid, "category_id": group_id, "sku": sku, "name": name, "full_name": "",
                    "unit": unit, "weight_kg": weight, "volume_m3": volume,
                })
                prices.append({"product_id": pid, "retail": retail, "wholesale": wholesale})
                stock.append({"product_id": pid, "quantity": qty})
    return {"categories": categories, "products": products, "prices": prices, "stock": stock}
