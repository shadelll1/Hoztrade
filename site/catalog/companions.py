def companions(product, limit=4):
    """До limit товаров из других групп, которые берут вместе с product; в наличии — первыми."""
    name = product.title.lower()
    words = next((wanted for keys, wanted in RULES if any(k in name for k in keys)), ())
    if not words:
        return []
    match = Q()
    rank = []
    # Ранг 2n — название начинается со слова («Плинтус ПВХ»), 2n+1 — слово внутри («Уголок для плинтуса»)
    for n, word in enumerate(words):
        match |= Q(search_text__contains=word)
        rank.append(When(search_text__startswith=word, then=Value(2 * n)))
    for n, word in enumerate(words):
        rank.append(When(search_text__contains=word, then=Value(2 * n + 1)))
    qs = (Product.objects.published().filter(match, price_retail__gt=0).exclude(pk=product.pk)
          .annotate(rule=Case(*rank, default=Value(2 * len(words)), output_field=IntegerField()))
          .select_related("category").order_by("rule", "-stock", "name"))
    # По одному товару на каждое правило, затем — остальные: «грунтовка, миксер, ведро», а не три грунтовки.
    picked, seen = [], set()
    # Тот же товар в другом исполнении (ламинат другого цвета) — не сопутствующий: его покажет «Ещё в разделе».
    first = name.split()[0]
    candidates = [p for p in qs[:40]
                  if not (p.category_id == product.category_id and p.title.lower().split()[0] == first)]
    for p in candidates:
        if p.rule // 2 not in seen:
            picked.append(p)
            seen.add(p.rule // 2)
    for p in candidates:
        if len(picked) >= limit:
            break
        if p not in picked:
            picked.append(p)
    return picked[:limit]
