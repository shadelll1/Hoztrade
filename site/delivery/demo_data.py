"""Демо-зоны, автопарк и тарифы в формате API обмена — те же, что создаёт в 1С команда «Заполнить демо-каталог».

ID детерминированные (uuid5), повторная загрузка обновляет. Когда доставка приходит из 1С, демо-зоны и машины
выключаются полной загрузкой.
"""
import uuid

NS = uuid.UUID("2b7f5d0e-8c41-4a3b-9e6f-5a1d0c9b8e10")

# Наименование, описание
ZONES = [
    ("Чебоксары", "В черте города"),
    ("Новочебоксарск", "Новочебоксарск и пригород до 15 км"),
    ("Пригород до 30 км", "Кугеси, Ишлеи, Лапсары, Шоршелы и другие населённые пункты до 30 км"),
    ("Межгород до 60 км", "Цивильск, Мариинский Посад, Козловка и другие до 60 км"),
]

# Наименование, грузоподъёмность т, объём кузова м³
TRUCKS = [
    ("ГАЗель Next, борт 1,5 т", 1.5, 9),
    ("ГАЗон Next, борт 3 т", 3, 18),
    ("ISUZU, борт 5 т", 5, 30),
    ("КАМАЗ, борт 10 т", 10, 36),
    ("КАМАЗ с полуприцепом 20 т", 20, 82),
]

# Стоимость рейса по зонам, в порядке машин
PRICES = {
    "Чебоксары": [800, 1200, 1800, 2800, 4500],
    "Новочебоксарск": [1100, 1500, 2200, 3300, 5200],
    "Пригород до 30 км": [1500, 2000, 2800, 4000, 6500],
    "Межгород до 60 км": [2500, 3200, 4200, 6000, 9000],
}


def _id(kind, name):
    return str(uuid.uuid5(NS, f"{kind}:{name}"))


def demo_payload():
    return {
        "zones": [{"id": _id("zone", name), "name": name, "description": desc, "sort": n * 10}
                  for n, (name, desc) in enumerate(ZONES, start=1)],
        "trucks": [{"id": _id("truck", name), "name": name, "capacity_t": cap, "volume_m3": vol}
                   for name, cap, vol in TRUCKS],
        "tariffs": [{"zone_id": _id("zone", zone), "truck_id": _id("truck", TRUCKS[i][0]), "price": price}
                    for zone, prices in PRICES.items() for i, price in enumerate(prices)],
    }
